use gold_band::config::DesktopLanguage;

pub struct Translator {
    language: DesktopLanguage,
}

impl Translator {
    pub fn new(language: DesktopLanguage) -> Self {
        Self { language }
    }

    pub fn tr(&self, key: &str) -> String {
        let translated = match self.language {
            DesktopLanguage::ZhCn => zh_cn(key),
            DesktopLanguage::ZhTw => zh_tw(key),
            DesktopLanguage::JaJp => ja(key),
            DesktopLanguage::KoKr => ko(key),
            DesktopLanguage::PtBr => pt(key),
            DesktopLanguage::Es => es(key),
            DesktopLanguage::En => None,
        };
        translated.or_else(|| en(key)).unwrap_or(key).to_string()
    }

    pub fn format(&self, key: &str, value: &str) -> String {
        self.tr(key).replace("{value}", value)
    }
}

